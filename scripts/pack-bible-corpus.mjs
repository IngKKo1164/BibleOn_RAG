import './lib/workspace.mjs';
// Bundle the same Bible text below the Edge Function source-size limit.
import { readFileSync, writeFileSync } from 'node:fs';
import { brotliCompressSync, brotliDecompressSync, constants } from 'node:zlib';
import { createHash } from 'node:crypto';
import assert from 'node:assert/strict';
const input = readFileSync(new URL('../server/data/krv.json', import.meta.url));
const compressed = brotliCompressSync(input, { params: { [constants.BROTLI_PARAM_QUALITY]: 11 } });
assert.deepEqual(brotliDecompressSync(compressed), input);
const checksum = createHash('sha256').update(input).digest('hex');
const source = `// Generated by scripts/pack-bible-corpus.mjs. Do not edit.\nimport { brotliDecompressSync } from 'node:zlib';\nexport const CORPUS_SHA256 = '${checksum}';\nconst packed = '${compressed.toString('base64')}';\nlet corpusPromise;\nexport function loadPackedBibleCorpus() {\n  return corpusPromise ??= (async () => {\n    const bytes = Uint8Array.from(atob(packed), c => c.charCodeAt(0));\n    return JSON.parse(new TextDecoder().decode(brotliDecompressSync(bytes)));\n  })();\n}\n`;
writeFileSync(new URL('../server/data/krv-packed.mjs', import.meta.url), source);
console.log(JSON.stringify({ sourceBytes:input.length, packedModuleBytes:Buffer.byteLength(source), checksum }));
